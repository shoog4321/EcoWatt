"""Lets tests import app modules when httpx is not installed (the sandbox has no network)."""
import sys
import types

try:
    import httpx  # noqa: F401
except ImportError:
    stub = types.ModuleType("httpx")
    class HTTPError(Exception): ...
    class ConnectError(HTTPError): ...
    class TimeoutException(HTTPError): ...
    class ConnectTimeout(TimeoutException): ...
    class ReadTimeout(TimeoutException): ...
    class RemoteProtocolError(HTTPError): ...
    stub.AsyncClient = type("AsyncClient", (), {})
    for c in (HTTPError, ConnectError, TimeoutException, ConnectTimeout, ReadTimeout, RemoteProtocolError):
        setattr(stub, c.__name__, c)
    sys.modules["httpx"] = stub
